function addMessage(text, sender) {
    const wrapper = document.createElement("div");
    wrapper.className = `message ${sender}`;

    const bubble = document.createElement("div");
    bubble.className = "message-bubble";
    bubble.textContent = text;

    const time = document.createElement("span");
    time.className = "message-time";
    time.textContent = new Date().toLocaleTimeString(
        currentLanguage === "ar" ? "ar" : "en",
        { hour: "2-digit", minute: "2-digit" }
    );

    wrapper.appendChild(bubble);
    wrapper.appendChild(time);
    messagesContainer.appendChild(wrapper);

    messagesContainer.scrollTop = messagesContainer.scrollHeight;
}


function renderQuickQuestions() {
    const data = translations[currentLanguage];

    quickQuestionsContainer.replaceChildren();

    data.questions.forEach((question, index) => {
        const button = document.createElement("button");

        button.type = "button";
        button.className = "quick-question";
        button.textContent = question;

        button.addEventListener("click", () => {
            askQuestion(question, index);
        });

        quickQuestionsContainer.appendChild(button);
    });
}


function updateLanguage() {
    const data = translations[currentLanguage];

    document.documentElement.lang = currentLanguage;
    document.documentElement.dir =
        currentLanguage === "ar" ? "rtl" : "ltr";

    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.dataset.i18n;

        if (data[key] !== undefined) {
            element.textContent = data[key];
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
        const key = element.dataset.i18nPlaceholder;

        if (data[key] !== undefined) {
            element.placeholder = data[key];
        }
    });

    languageToggle.textContent =
        currentLanguage === "ar" ? "English" : "العربية";

    sendLabel.textContent = data.send;

    renderQuickQuestions();

    messagesContainer.replaceChildren();
    addMessage(data.welcome, "bot");
}


function normalizeText(text) {
    return text
        .toLowerCase()
        .normalize("NFKC")
        .replace(/[\u064B-\u065F\u0670\u0640]/g, "")
        .replace(/[أإآٱ]/g, "ا")
        .replace(/ى/g, "ي")
        .replace(/ة/g, "ه")
        .replace(/[؟?!.,،؛:()[\]{}"'`]/g, " ")
        .replace(/\s+/g, " ")
        .trim();
}


