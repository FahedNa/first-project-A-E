function findAnswerIndex(question) {
    const text = normalizeText(question);
    const data = translations[currentLanguage];

    // Exact question match
    const exactIndex = data.questions.findIndex(
        item => normalizeText(item) === text
    );

    if (exactIndex !== -1) {
        return exactIndex;
    }

    const groups = keywordGroups[currentLanguage];

    let bestIndex = -1;
    let bestLength = 0;

    groups.forEach((keywords, index) => {
        keywords.forEach(keyword => {
            const normalizedKeyword = normalizeText(keyword);

            if (
                normalizedKeyword.length >= 3 &&
                text.includes(normalizedKeyword) &&
                normalizedKeyword.length > bestLength
            ) {
                bestIndex = index;
                bestLength = normalizedKeyword.length;
            }
        });
    });

    return bestIndex;
}


function askQuestion(question, knownIndex = null) {
    const cleanedQuestion = question.trim();

    if (!cleanedQuestion) {
        addMessage(translations[currentLanguage].empty, "bot");
        return;
    }

    addMessage(cleanedQuestion, "user");

    const index = knownIndex !== null
        ? knownIndex
        : findAnswerIndex(cleanedQuestion);

    const data = translations[currentLanguage];

    const answer =
        index >= 0 && index < data.answers.length
            ? data.answers[index]
            : data.unknown;

    window.setTimeout(() => {
        addMessage(answer, "bot");
    }, 250);
}


chatForm.addEventListener("submit", event => {
    event.preventDefault();

    const question = userInput.value.trim();

    if (!question) {
        addMessage(translations[currentLanguage].empty, "bot");
        return;
    }

    askQuestion(question);
    userInput.value = "";
    userInput.focus();
});


